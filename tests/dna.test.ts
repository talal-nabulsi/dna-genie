import { expect, it } from "vitest";
import { zipSync, strToU8 } from "fflate";
import { parseDNAFile } from "@/lib/dna/parse";

const me = "# This data file generated by 23andMe\r\n# rsid\tchromosome\tposition\tgenotype\r\nrs4988235\t2\t136608646\tAG\r\nrs1\t1\t1\tAA\r\nrs671\t12\t112241766\t--\r\nrs4680\t22\t19951271\tGG";
const anc = "#AncestryDNA raw data download\nrsid\tchromosome\tposition\tallele1\tallele2\nrs4988235\t2\t136608646\tA\tG\nrs671\t12\t112241766\t0\t0\n";

it("reads 23andMe, with CRLF and no last newline", async () => {
  const p = await parseDNAFile(new File([me], "g.txt"));
  expect(p.format).toBe("23andme"); expect(p.rows).toBe(4); expect([...p.snps]).toEqual([["rs4988235", "AG"], ["rs4680", "GG"]]);
});
it("reads AncestryDNA", async () => {
  const p = await parseDNAFile(new File([anc], "a.txt"));
  expect(p.format).toBe("ancestrydna"); expect([...p.snps]).toEqual([["rs4988235", "AG"]]);
});
it("reads a zip", async () => {
  const z = zipSync({ "genome.txt": strToU8(me) });
  const p = await parseDNAFile(new File([z as BlobPart], "genome.zip"));
  expect(p.snps.get("rs4680")).toBe("GG");
});
it("turns away other files", async () => {
  await expect(parseDNAFile(new File(["hello\nworld"], "x.txt"))).rejects.toThrow(/does not look like/);
});
